/** Réplique suivante d'un héros (la citation de sa fiche, puis ses trois répliques). */
export function heroLine(heroId: string, quote: string, i: number): string {
  const q = /^«\s*(.*?)\s*»$/.exec(quote)?.[1] ?? quote;
  const all = [q, ...(HERO_LINES[heroId] ?? [])];
  return all[((i % all.length) + all.length) % all.length];
}
